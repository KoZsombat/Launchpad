import { Router } from "express";
import type { CicdInfo } from "@launchpad/shared";
import { ApiError } from "../lib/errors";
import { requireParam } from "../lib/http";
import {
  WORKFLOW_PATH,
  commitWorkflowFile,
  generateWorkflow,
  parseGitHubRepo,
} from "../lib/github";
import { getWebhookSecret, requireAppRow } from "../services/apps";
import { getGithubToken, getPanelUrl } from "../services/settings";
import type { AppRow } from "../db/schema";

export const cicdRouter = Router();

function githubContext(app: AppRow) {
  if (app.sourceType !== "github" || !app.repoUrl) {
    throw new ApiError(400, "CI/CD is only available for GitHub-sourced apps.");
  }
  const repo = parseGitHubRepo(app.repoUrl);
  if (!repo) {
    throw new ApiError(400, "Only repositories hosted on github.com support GitHub Actions.");
  }
  const workflowYaml = generateWorkflow({
    appId: app.id,
    panelUrl: getPanelUrl(),
    repoUrl: app.repoUrl,
    branch: app.branch ?? "main",
    buildContext: app.buildContext ?? ".",
    dockerfilePath: app.dockerfilePath ?? "Dockerfile",
  });
  return { repo, workflowYaml };
}

function buildCicdInfo(app: AppRow): CicdInfo {
  const { repo, workflowYaml } = githubContext(app);
  const panelUrl = getPanelUrl();
  const webhookSecret = getWebhookSecret(app);
  return {
    appId: app.id,
    panelUrl,
    webhookUrl: `${panelUrl}/api/hooks/deploy/${app.id}`,
    webhookSecret,
    workflowPath: WORKFLOW_PATH,
    workflowYaml,
    secrets: [
      {
        name: "LAUNCHPAD_WEBHOOK_SECRET",
        value: webhookSecret,
        description: "Per-app webhook secret generated by Launchpad.",
      },
      {
        name: "CF_ACCESS_CLIENT_ID",
        value: "",
        description:
          "Client ID of the Cloudflare Access service token for panel.your-domain.",
      },
      {
        name: "CF_ACCESS_CLIENT_SECRET",
        value: "",
        description:
          "Client secret of the Cloudflare Access service token for panel.your-domain.",
      },
    ],
    githubPushWebhookUrl: `${panelUrl}/api/hooks/github/${app.id}`,
    githubTokenSet: Boolean(getGithubToken()),
    repoOwner: repo.owner,
    repoName: repo.repo,
  };
}

cicdRouter.get("/apps/:id/cicd", (req, res) => {
  const app = requireAppRow(requireParam(req.params, "id"));
  res.json({ cicd: buildCicdInfo(app) });
});

cicdRouter.get("/apps/:id/github-push", (req, res) => {
  const app = requireAppRow(requireParam(req.params, "id"));
  if (!app.repoUrl) throw new ApiError(400, "This project has no GitHub repository.");
  const repo = parseGitHubRepo(app.repoUrl);
  res.json({
    githubPush: {
      appId: app.id,
      branch: app.branch ?? "main",
      webhookUrl: `${getPanelUrl()}/api/hooks/github/${app.id}`,
      webhookSecret: getWebhookSecret(app),
      repoOwner: repo?.owner ?? null,
      repoName: repo?.repo ?? null,
    },
  });
});

cicdRouter.post("/apps/:id/cicd/workflow", async (req, res) => {
  const app = requireAppRow(requireParam(req.params, "id"));
  const { repo, workflowYaml } = githubContext(app);
  const token = getGithubToken();
  if (!token) {
    res.json({
      committed: false,
      error: "Add a GitHub token in Settings to commit the workflow automatically.",
      path: WORKFLOW_PATH,
      yaml: workflowYaml,
    });
    return;
  }
  const result = await commitWorkflowFile({
    repo,
    branch: app.branch ?? "main",
    token,
    yaml: workflowYaml,
  });
  res.json({
    ...result,
    path: WORKFLOW_PATH,
    yaml: workflowYaml,
  });
});
